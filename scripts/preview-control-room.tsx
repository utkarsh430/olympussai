/**
 * An interactive, browser-real harness for the control-room console.
 *
 * ─── WHY THIS EXISTS ─────────────────────────────────────────────────────
 *
 * The console cannot be opened the ordinary way in a review environment: every
 * ops page is behind `requireOpsRolePage`, which needs a real Supabase session
 * for one of the seeded operator accounts, and the end-to-end suite's default
 * origin is the port the captain's live app already occupies. Reviewing the
 * screen by taking that port, or by weakening the guard, would both be wrong.
 *
 * So this mounts the REAL ControlRoomConsole - the same component the guarded
 * page renders, with the real design system and the real Tailwind build - in a
 * real browser, and stubs only the network. Every interaction under review
 * (tab switching, the engine panel's staging and confirmation, the approval
 * queue's approve and reject, the kill-switch form, prefill into the command
 * form) is the shipped code path, and the requests it makes are captured so
 * they can be asserted rather than eyeballed.
 *
 * ─── WHAT IS REAL AND WHAT IS NOT ────────────────────────────────────────
 *
 * Sibling `preview-control-room-data.json` is generated by
 * `scripts/capture-control-room-fixture.ts` from the captain's own running
 * control service: real corridor ids, real UPSRTC registration numbers, a real
 * solve, real daily KPI rows. The scenarios below say which is which, on the
 * page, in a banner - a harness that looked like production would be the same
 * dishonesty this whole phase exists to remove.
 *
 * Run it with scripts/serve-control-room-preview.mjs, which bundles this entry
 * with esbuild and serves it on a scratch port.
 */
