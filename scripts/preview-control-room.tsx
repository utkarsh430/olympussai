function overviewFor(scenario: Scenario): ControlRoomOverview {
  const degraded = scenario === 'degraded';
  return {
    fetchedAt: new Date().toISOString(),
    corridorsPlaceholder: undefined,
    routeDirections: fixture.corridors,
    selectedRouteDirectionId: CORRIDOR,
    fleet: degraded
      ? { reporting: 0, source: 'unavailable', stale: true, error: 'upstream feed did not respond' }
      : { reporting: 9170, source: 'live', stale: false, error: null },
    observability: degraded
      ? { ok: false, stale: true, error: 'control service timed out' }
      : { ok: true, stale: false, error: null },
    headway: degraded ? null : (fixture.headway as ControlRoomOverview['headway']),
    incidents: [],
    dailyKpi: degraded
      ? { ok: false, row: null }
      : { ok: true, row: fixture.kpiRow as ControlRoomOverview['dailyKpi']['row'] },
    guardrails: degraded ? { ok: false, total: 0, critical: 0 } : { ok: true, total: 0, critical: 0 },
    killSwitches:
      scenario === 'killswitch'
        ? {
            ok: true,
            active: [
              {
                id: 'ks-live-1',
                scope: 'network' as const,
                routeDirectionId: null,
                engagedAt: new Date(Date.now() - 90_000).toISOString(),
                engagedBy: 'control@upsrtc.example',
                reason: 'Statewide comms degradation — holding all automated commands.',
                disengagedAt: null,
                disengagedBy: null,
                disengageReason: null,
              },
            ],
          }
        : { ok: true, active: [] },
  } as unknown as ControlRoomOverview;
}

type Scenario = 'proposal' | 'live-rejected' | 'degraded' | 'killswitch';

let scenario: Scenario = (new URLSearchParams(location.search).get('scenario') as Scenario) || 'proposal';

const realFetch = window.fetch.bind(window);
window.fetch = (async (input: RequestInfo | URL, init?: RequestInit) => {
  const url = typeof input === 'string' ? input : input.toString();
  const method = init?.method ?? 'GET';
  let body: unknown = null;
  try {
    body = init?.body ? JSON.parse(String(init.body)) : null;
  } catch {
    body = String(init?.body ?? '');
  }
  if (url.startsWith('/api/')) window.__REQUESTS__.push({ url, method, body });

  const json = (payload: unknown, status = 200) =>
    new Response(JSON.stringify(payload), { status, headers: { 'content-type': 'application/json' } });

  if (url.startsWith('/api/ops/control-room/overview')) return json(overviewFor(scenario));
  if (url.startsWith('/api/ops/control-room/recommendations')) {
    if (scenario === 'degraded') {
      return json(
        { error: { code: 'CONTROL_SERVICE_ERROR', message: 'Unexpected response shape from /v1/mpc/solve' } },
        502,
      );
    }
    const result = scenario === 'proposal' ? proposed : liveRejected;
    const withKill =
      scenario === 'killswitch'
        ? {
            ...proposed,
            commandsBlockedBy: {
              scope: 'network' as const,
              routeDirectionId: null,
              reason: 'Statewide comms degradation — holding all automated commands.',
              engagedAt: new Date(Date.now() - 90_000).toISOString(),
            },
          }
        : result;
    return json({ ...withKill, solvedAt: new Date().toISOString() });
  }
  if (url.startsWith('/api/ops/dispatcher/approvals')) {
    return json({ actions: scenario === 'live-rejected' ? [DISRUPTIVE_APPROVAL] : [APPROVAL, DISRUPTIVE_APPROVAL] });
  }
  if (url.startsWith('/api/ops/control-room/commands/') && method === 'GET') {
    return json({
      command: {
        id: 'cmd-1',
        status: 'acknowledged',
        deliveredAt: new Date(Date.now() - 30_000).toISOString(),
        acknowledgedAt: new Date(Date.now() - 20_000).toISOString(),
        ackOutcome: 'accept',
        acknowledgementReason: null,
      },
      auditLog: [
        { id: 'a1', eventType: 'created', actorType: 'control_room', actorId: 'op-1', reason: null, occurredAt: new Date().toISOString() },
        { id: 'a2', eventType: 'delivered', actorType: 'system', actorId: null, reason: null, occurredAt: new Date().toISOString() },
      ],
    });
  }
  if (url.startsWith('/api/ops/control-room/commands') && method === 'POST') {
    return json({ ok: true, commandId: 'cmd-preview-1', status: 'delivered', expiresAt: 'in 120s', auditEventId: 'audit-1' }, 201);
  }
  if (url.includes('/reject')) return json({ ok: true });
  if (url.startsWith('/api/ops/control-room/kill-switches')) {
    if (method === 'POST') return json({ ok: true }, 201);
    return json({ active: overviewFor(scenario).killSwitches.active });
  }
  if (url.startsWith('/api/ops/fleet/map')) {
    return json({
      vehicles: fixture.vehicles,
      incidents: [],
      scopeLabel: 'all depots',
      source: 'live',
      stale: false,
      fetchedAt: new Date().toISOString(),
      error: null,
      controlServiceError: null,
    });
  }
  if (url.startsWith('/api/ops/fleet/breakdown-reports')) {
    return json({
      reports: [
        {
          id: 'br-1',
          vehicleId: 'UP78KN2230',
          reportedAt: new Date(Date.now() - 15 * 60_000).toISOString(),
          category: 'mechanical',
          severity: 'high',
          notes: 'Air brake pressure dropping on the Agra Expressway run.',
          driverEmail: 'driver1@upsrtc.example',
          depotName: 'Agra',
          status: 'open',
        },
      ],
      nextCursor: null,
    });
  }
  if (url.startsWith('/api/ops/control-room/copilot')) {
    return json({ narrative: 'Preview harness: the copilot is not called from this harness.', citations: [] });
  }
  return realFetch(input as RequestInfo, init);
}) as typeof window.fetch;

function Harness() {
  const [, force] = useState(0);
  return (
    <>
      <div
        style={{
          position: 'fixed',
          bottom: 0,
          left: 0,
          right: 0,
          zIndex: 9999,
          background: '#3a1d05',
          color: '#ffd6a5',
          borderTop: '1px solid #7a4a12',
          font: '11px ui-monospace, monospace',
          padding: '6px 12px',
          display: 'flex',
          gap: '10px',
          alignItems: 'center',
        }}
      >
        <strong>REVIEW HARNESS — network stubbed, not a live console.</strong>
        <span>
          corridors / registrations / solve / KPI captured from the live control service at {fixture.capturedAt}.
        </span>
        <span style={{ marginLeft: 'auto' }}>scenario:</span>
        {(['proposal', 'live-rejected', 'killswitch', 'degraded'] as Scenario[]).map((id) => (
          <button
            key={id}
            id={`scenario-${id}`}
            onClick={() => {
              scenario = id;
              force((n) => n + 1);
            }}
            style={{
              background: scenario === id ? '#ffd6a5' : 'transparent',
              color: scenario === id ? '#3a1d05' : '#ffd6a5',
              border: '1px solid #7a4a12',
              borderRadius: 3,
              padding: '2px 8px',
              cursor: 'pointer',
            }}
          >
            {id}
          </button>
        ))}
      </div>
      <ControlRoomConsole
        key={scenario}
        email="control.room@upsrtc.example"
        initialOverview={overviewFor(scenario)}
        initialOverviewError={null}
        initialActiveKillSwitches={overviewFor(scenario).killSwitches.active}
        initialTab="decisions"
        fleetPanel={<div style={{ padding: 16 }}>Fleet roster renders on the server; not part of this harness.</div>}
        reportsPanel={<div style={{ padding: 16 }}>Breakdown reports panel fetches on mount.</div>}
      />
    </>
  );
}

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <Harness />
  </StrictMode>,
);
