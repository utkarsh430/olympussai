// Fitting the demand profile instead of inventing it.
//
// The harness's headline caveat has always been that running time, dwell and
// boarding rate are invented, so a gain tuned against them is tuned against a
// fiction. These tests pin the recovery: `beta_h` fitted from `stop_visits`
// divided by an assumed seconds-per-boarding yields a MEASURED arrival rate,
// with no ticketing data anywhere in the chain.
import { describe, it, expect } from 'vitest';
import {
  calibrateFromVisits,
  describeCalibration,
  isCalibrated,
  DEFAULT_SECONDS_PER_BOARDING,
} from '../../src/evaluation/calibrate.js';
import { selectCorridors } from '../../src/evaluation/corridors.js';
import { runCell } from '../../src/evaluation/runner.js';
import { parseExperimentSpec, resolveInputs } from '../../src/evaluation/spec.js';
import type { StopVisitRecord } from '../../src/headway/stopHeadway.js';
import type { CorridorInputs } from '../../src/rehearsal/corridor.js';

const EPOCH = Date.parse('2026-08-01T00:00:00.000Z');

/**
 * A visit log generated by a KNOWN dwell law, so the fit can be checked
 * against the truth that produced it rather than against itself.
 *
 * The law is self-referential and has to be solved rather than evaluated.
 * `buildDwellObservations` pairs a dwell with the interval since the PREVIOUS
 * bus departed the same stop, and that interval ends at this bus's own
 * departure - which is what the dwell determines:
 *
 *   dwell     = beta0 + betaH x (departure - previousDeparture)
 *   departure = arrival + dwell
 *
 * so  departure = (arrival + beta0 - betaH x previousDeparture) / (1 - betaH).
 *
 * Generating from that closed form makes the relationship the fitter looks
 * for hold EXACTLY, which is the only way an exact-recovery assertion means
 * anything. A first pass that simply picked a headway and multiplied by it
 * produced a log whose recorded gaps were nothing like the headways the
 * dwells were built from, and the fit dutifully returned beta0 = -1738.
 */
function visitLog(
  corridor: CorridorInputs,
  { beta0, betaHeadway, trips = 30, linkSeconds = 300 }:
    { beta0: number; betaHeadway: number; trips?: number; linkSeconds?: number },
): StopVisitRecord[] {
  const visits: StopVisitRecord[] = [];
  const lastDepartureAtStop = new Map<string, number>();

  for (let trip = 0; trip < trips; trip++) {
    // Dispatch intervals are deliberately uneven: a constant headway gives the
    // regression no slope to find.
    const dispatch = EPOCH + trip * 900_000 + (trip % 7) * 120_000;
    let clock = dispatch;

    corridor.stops.forEach((stop, index) => {
      if (index > 0) clock += linkSeconds * 1000;
      const arrivalSeconds = clock / 1000;
      const previousDeparture = lastDepartureAtStop.get(stop.stopId);
      const departureSeconds =
        previousDeparture === undefined
          ? arrivalSeconds + beta0
          : (arrivalSeconds + beta0 - betaHeadway * previousDeparture) / (1 - betaHeadway);

      visits.push({
        vehicleId: `veh-${trip}`,
        stopId: stop.stopId,
        routeDirectionId: corridor.routeDirectionId,
        arrivedAt: new Date(arrivalSeconds * 1000).toISOString(),
        departedAt: new Date(departureSeconds * 1000).toISOString(),
        tripId: `trip-${trip}`,
      });

      lastDepartureAtStop.set(stop.stopId, departureSeconds);
      clock = departureSeconds * 1000;
    });
  }
  return visits;
}

async function corridor(): Promise<CorridorInputs> {
  const { corridors } = await selectCorridors({ source: 'synthetic', count: 1 });
  const first = corridors[0];
  if (!first) throw new Error('no corridor');
  return first;
}

describe('calibrating a corridor from recorded stop visits', () => {
  it('recovers the dwell law that generated the log', async () => {
    const c = await corridor();
    const calibration = calibrateFromVisits(c, visitLog(c, { beta0: 18, betaHeadway: 0.05 }));

    expect(calibration.stops.length).toBeGreaterThan(0);
    const stop = calibration.stops[0]!;
    expect(stop.beta0Seconds).toBeCloseTo(18, 1);
    expect(stop.betaHeadway).toBeCloseTo(0.05, 3);
    expect(stop.rSquared).toBeGreaterThan(0.99);
  });

  // The whole point: an arrival rate with no ticketing data in the chain.
  // beta_h = beta_b x lambda, so lambda = beta_h / beta_b.
  it('derives a boarding rate from beta_h without any boarding count', async () => {
    const c = await corridor();
    const betaHeadway = 0.05;
    const calibration = calibrateFromVisits(c, visitLog(c, { beta0: 18, betaHeadway }));
    const expectedPerMinute = (betaHeadway / DEFAULT_SECONDS_PER_BOARDING) * 60;
    expect(calibration.stops[0]?.boardingRatePerMinute).toBeCloseTo(expectedPerMinute, 3);
  });

  // The number that says whether a corridor needs control at all.
  // Both values stay well below the point where the generator itself runs
  // away: at beta_h = 0.4 the closed form divides by 0.6 and the simulated
  // service comes apart within a few trips, which is not a fixture problem
  // but the very instability the eigenvalue is measuring - a corridor at 1.4
  // does not have a steady state to fit.
  it('reports the headway amplification eigenvalue 1 + beta_h', async () => {
    const c = await corridor();
    const calm = calibrateFromVisits(c, visitLog(c, { beta0: 18, betaHeadway: 0.02 }));
    const volatile = calibrateFromVisits(c, visitLog(c, { beta0: 18, betaHeadway: 0.15 }));
    expect(calm.medianAmplification).toBeCloseTo(1.02, 2);
    // Recovered approximately rather than exactly, and the gap widens with
    // beta_h. Downstream stops inherit the upstream dwells, so the spread of
    // headways each stop sees is not the spread the generator dispatched -
    // which is amplification doing what it is named for. The number that has
    // to be trustworthy is the ORDER of magnitude and the ordering, both of
    // which decide whether a corridor needs control; the exact-recovery
    // assertion lives in the first test, at a beta_h the process is stable at.
    expect(volatile.medianAmplification!).toBeGreaterThan(1.1);
    expect(volatile.medianAmplification!).toBeLessThan(1.2);
    expect(volatile.medianAmplification!).toBeGreaterThan(calm.medianAmplification!);
  });

  it('fits link travel times from consecutive visits by the same vehicle', async () => {
    const c = await corridor();
    const calibration = calibrateFromVisits(c, visitLog(c, { beta0: 18, betaHeadway: 0.05, linkSeconds: 420 }));
    expect(calibration.linksFitted).toBeGreaterThan(0);
    // Keyed by the stop the link ARRIVES at, matching `links[i]` being the
    // leg into `stops[i]`. Asserted on a named link rather than whichever the
    // map happens to yield first.
    const secondStopId = c.stops[1]!.stopId;
    expect(calibration.overrides.linkByToStopId?.get(secondStopId)?.meanSeconds).toBeCloseTo(420, 0);
  });

  // A negative slope means dwell SHRANK as the gap grew, which no boarding
  // process produces. Dividing it by beta_b would hand the simulator a
  // negative arrival rate, so the stop is dropped rather than fitted.
  it('drops a stop whose fitted slope is not a boarding process', async () => {
    const c = await corridor();
    const calibration = calibrateFromVisits(c, visitLog(c, { beta0: 60, betaHeadway: -0.05 }));
    expect(calibration.stops).toHaveLength(0);
    expect(isCalibrated(calibration)).toBe(false);
  });

  it('stays modelled, and says so, when nothing was recorded', async () => {
    const c = await corridor();
    const calibration = calibrateFromVisits(c, []);
    expect(calibration.stops).toHaveLength(0);
    expect(isCalibrated(calibration)).toBe(false);
    expect(describeCalibration(calibration)).toContain('MODELLED');
    expect(describeCalibration(calibration)).toContain('invented default');
  });

  // The dangerous case: enough fitted to look measured, not enough to be it.
  it('names a partial calibration as partial rather than rounding it up', async () => {
    const c = await corridor();
    const visits = visitLog(c, { beta0: 18, betaHeadway: 0.05 });
    const firstStopId = c.stops[0]!.stopId;
    const partial = calibrateFromVisits(c, visits.filter((v) => v.stopId === firstStopId));
    expect(partial.stops).toHaveLength(1);
    expect(isCalibrated(partial)).toBe(false);
    expect(describeCalibration(partial)).toContain('PARTIALLY CALIBRATED');
  });

  it('states the assumption every derived rate rests on', async () => {
    const c = await corridor();
    const description = describeCalibration(
      calibrateFromVisits(c, visitLog(c, { beta0: 18, betaHeadway: 0.05 })),
    );
    expect(description).toContain('ASSUMED');
    expect(description).toContain('Alighting fraction');
  });

  it('feeds the fitted profile into a run, changing the simulated corridor', async () => {
    const c = await corridor();
    const spec = parseExperimentSpec({
      name: 'calibrated',
      corridors: { source: 'synthetic', count: 1 },
      scenarios: ['none'],
      seeds: { count: 1, base: 99 },
      arms: [{ name: 'as-deployed', policyOverrides: {} }],
    });
    const inputs = resolveInputs(spec, 99, 'none');
    const calibration = calibrateFromVisits(c, visitLog(c, { beta0: 40, betaHeadway: 0.3 }));

    const modelled = runCell(c, spec.arms[0]!, inputs);
    const calibrated = runCell(c, spec.arms[0]!, inputs, undefined, calibration);

    // A corridor with a far steeper dwell law is a different corridor. If
    // these matched, the calibration would be decorative.
    expect(calibrated.baseline.totalBoardings).not.toBe(modelled.baseline.totalBoardings);
  });
});
